import { TraderApiClient, TraderApiResult, requiredField } from '../../api-client/trader-api-client';
import { TRADER_API_PATH } from '../../constant/trader-api/trader-api-path-constant';
import { buildPath } from '../../helper/api-path-helper';

interface SfdResult extends TraderApiResult {
    sfd_number?: string;
    movement_reference_number?: string;
}

export interface SfdSummary {
    sfdNumber: string;
    status: string;
    movementReferenceNumber: string;
}

export class SimplifiedFrontierDeclarationService {
    constructor(private readonly api: TraderApiClient) { }

    async findSfdByConsignment(consignmentNumber: string): Promise<string> {
        const call = `Look up the SFD generated by ${consignmentNumber}`;
        const result = await this.api.read<SfdResult>(
            buildPath(TRADER_API_PATH.SfdByConsignmentNumber, { consignmentNumber }), call
        );

        return requiredField(result, 'sfd_number', call);
    }

    async readSfd(sfdNumber: string): Promise<SfdSummary> {
        const call = `Read SFD ${sfdNumber}`;
        const result = await this.api.read<SfdResult>(
            buildPath(TRADER_API_PATH.SfdByReference, { reference: sfdNumber }), call
        );

        return {
            sfdNumber,
            status: requiredField(result, 'status', call),
            movementReferenceNumber: result.movement_reference_number ?? '',
        };
    }
}
