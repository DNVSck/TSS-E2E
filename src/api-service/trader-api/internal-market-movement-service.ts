import { TraderApiClient, TraderApiResult, requiredField } from '../../api-client/trader-api-client';
import { TRADER_API_PATH } from '../../constant/trader-api/trader-api-path-constant';
import { buildPath } from '../../helper/api-path-helper';

interface InternalMarketMovementResult extends TraderApiResult {
    error_message?: string;
    immi_number?: string;
    movement_reference_number?: string;
    declaration_category?: string;
}

export interface InternalMarketMovementSummary {
    reference: string;
    status: string;
    errorMessage: string;
    movementReferenceNumber: string;
}

export class InternalMarketMovementService {
    constructor(private readonly api: TraderApiClient) { }

    async findImmiByConsignment(consignmentNumber: string): Promise<string> {
        const call = `Look up the IMMI generated by ${consignmentNumber}`;
        const result = await this.api.read<InternalMarketMovementResult>(
            buildPath(
                TRADER_API_PATH.InternalMarketMovementByConsignmentNumber, { consignmentNumber }
            ), call
        );

        return requiredField(result, 'immi_number', call);
    }

    /**
     * Answers for the consignment's own reference as well as the IMMI number, so a
     * caller that has just submitted a consignment does not need to find the IMMI first.
     * Asked for a consignment reference it reports that consignment, and its glr_number
     * echoes the reference asked for rather than naming an IMMI.
     */
    async readByReference(reference: string): Promise<InternalMarketMovementSummary> {
        const call = `Read the declaration generated by ${reference}`;
        const result = await this.api.read<InternalMarketMovementResult>(
            buildPath(TRADER_API_PATH.InternalMarketMovementByReference, { reference }), call
        );

        return {
            reference: result.reference ?? reference,
            status: requiredField(result, 'status', call),
            errorMessage: result.error_message ?? '',
            movementReferenceNumber: result.movement_reference_number ?? '',
        };
    }
}
